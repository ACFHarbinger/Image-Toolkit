"""Generate bridge-contract types and the contract-hash manifest.

Source of truth: contracts/schemas/**/*.json + contracts/methods.toml.
Outputs (all committed; CI freshness-checks via ``--check``):

- generated/ts/<stem>.ts + index.ts      (webview / EventHub consumers)
- generated/python/contracts_generated.py   (middleware consumers)
- generated/rust/contracts.rs            (wired into src-tauri by #876)
- ../frontend/src/eventhub/generated/channels.ts  (EventHub registry, #878)
- CONTRACTS.sha256                       (per-source hashes + total)

Stdlib-only: the CI freshness check runs in the lint job with no extra
dependencies. Deep schema validation lives in contracts/test (jsonschema).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import tomllib
from pathlib import Path
from typing import Any, NamedTuple

ROOT = Path(__file__).resolve().parent
SCHEMAS = ROOT / "schemas"

DRAFT = "https://json-schema.org/draft/2020-12/schema"
GENERATED_MARK = "GENERATED by contracts/generate.py"

KNOWN_KEYWORDS = {
    "$defs",
    "$id",
    "$ref",
    "$schema",
    "additionalProperties",
    "anyOf",
    "const",
    "description",
    "enum",
    "format",
    "items",
    "maximum",
    "maxLength",
    "minimum",
    "minLength",
    "oneOf",
    "pattern",
    "properties",
    "required",
    "title",
    "type",
    "uniqueItems",
}

SCALAR_TS = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}
SCALAR_PY = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "null": "None"}
SCALAR_RS = {"string": "String", "integer": "i64", "number": "f64", "boolean": "bool", "null": "()"}
RUST_ENUM_VALUE = re.compile(r"^[a-z][a-z0-9_]*$")


class Ref(NamedTuple):
    file: str  # schema file stem, e.g. "jobs"
    title: str


class SchemaFile:
    def __init__(self, stem: str, path: Path, raw: dict[str, Any]) -> None:
        self.stem = stem
        self.path = path
        self.raw = raw
        self.titles: dict[str, dict[str, Any]] = {}
        for title, sub in (raw.get("$defs") or {}).items():
            if isinstance(sub, dict):
                self.titles[title] = sub

    def find(self, title: str) -> dict[str, Any]:
        if title == self.raw.get("title"):
            return self.raw
        if title in self.titles:
            return self.titles[title]
        raise KeyError(f"{self.path.name}: no schema titled {title!r}")


def load_inputs() -> tuple[list[SchemaFile], dict[str, Any]]:
    paths = sorted(SCHEMAS.rglob("*.json"), key=lambda p: p.relative_to(SCHEMAS).as_posix())
    if not paths:
        sys.exit("no schema files found under contracts/schemas")
    schemas: list[SchemaFile] = []
    stems: set[str] = set()
    for path in paths:
        raw = json.loads(path.read_text(encoding="utf-8"))
        _check_sanity(path, raw)
        if path.stem in stems:
            sys.exit(f"duplicate schema file stem {path.stem!r}: stems must be unique across schemas/")
        stems.add(path.stem)
        schemas.append(SchemaFile(path.stem, path, raw))
    methods = tomllib.loads((ROOT / "methods.toml").read_text(encoding="utf-8"))
    return schemas, methods


def _check_sanity(path: Path, raw: Any) -> None:
    if not isinstance(raw, dict):
        sys.exit(f"{path}: root must be an object")
    if raw.get("$schema") != DRAFT:
        sys.exit(f"{path}: $schema must be {DRAFT}")
    if not raw.get("title"):
        sys.exit(f"{path}: missing title")
    unknown = set(raw) - KNOWN_KEYWORDS
    if unknown:
        sys.exit(f"{path}: unsupported keywords {sorted(unknown)} (generator whitelist)")


def resolve(
    ref: str, from_file: SchemaFile, by_stem: dict[str, SchemaFile]
) -> tuple[SchemaFile, str, dict[str, Any]]:
    """Resolve '#/pointer' (same file) or '<relative path>[#pointer]'.

    Cross-file refs must target the whole file (whose root title is used);
    pointers are restricted to '/$defs/<title>'.
    """
    file_part, _, pointer = ref.partition("#")
    target = from_file
    if file_part:
        target_path = (from_file.path.parent / file_part).resolve()
        target = next((s for s in by_stem.values() if s.path.resolve() == target_path), None)
        if target is None:
            sys.exit(f"{from_file.path.name}: $ref {ref!r} points outside schemas/")
    if pointer:
        if not pointer.startswith("/$defs/"):
            sys.exit(f"{from_file.path.name}: unsupported $ref pointer {ref!r} (only #/$defs/<title>)")
        title = pointer.removeprefix("/$defs/")
        sub = target.titles.get(title)
        if sub is None:
            sys.exit(f"{target.path.name}: no $defs entry {title!r}")
        return target, title, sub
    return target, target.raw["title"], target.raw


def _split_ref(ref: str) -> Ref:
    stem, _, title = ref.partition(".")
    if not stem or not title:
        sys.exit(f"methods.toml: malformed schema ref {ref!r} (want '<stem>.<Title>')")
    return Ref(stem, title)


def _root_title(by_stem: dict[str, SchemaFile], rel_path: str, key: str) -> str:
    stem = Path(rel_path).stem
    target = by_stem.get(stem)
    if target is None or not target.raw.get("title"):
        sys.exit(f"methods.toml: envelope.{key} points at schemas/{stem}.json with no root title")
    return target.raw["title"]


def _child_refs(node: Any, from_file: SchemaFile, by_stem: dict[str, SchemaFile]) -> list[Ref]:
    found: list[Ref] = []
    if isinstance(node, dict):
        if "$ref" in node:
            target, title, _ = resolve(node["$ref"], from_file, by_stem)
            found.append(Ref(target.stem, title))
        for key, value in node.items():
            if key != "$ref":
                found.extend(_child_refs(value, from_file, by_stem))
    elif isinstance(node, list):
        for item in node:
            found.extend(_child_refs(item, from_file, by_stem))
    return found


def collect_emittable(schemas: list[SchemaFile], methods: dict[str, Any]) -> dict[Ref, dict[str, Any]]:
    """Every titled schema reachable from methods.toml refs, by Ref."""
    by_stem = {s.stem: s for s in schemas}
    out: dict[Ref, dict[str, Any]] = {}
    stack: list[Ref] = []
    envelope = methods.get("envelope", {})
    for key in ("request", "response", "error", "event"):
        if key in envelope:
            stack.append(Ref(Path(envelope[key]).stem, _root_title(by_stem, envelope[key], key)))
    for row in methods.get("method", []):
        stack.extend(_split_ref(row[key]) for key in ("params", "result"))
    for row in methods.get("channel", []):
        stack.extend(_split_ref(row[key]) for key in ("payload", "snapshot"))
    while stack:
        ref = stack.pop()
        if ref in out:
            continue
        target = by_stem.get(ref.file)
        if target is None:
            sys.exit(f"methods.toml: unknown schema stem {ref.file!r}")
        sub = target.find(ref.title)
        out[ref] = sub
        stack.extend(child for child in _child_refs(sub, target, by_stem) if child not in out)
    return out


# ---------------------------------------------------------------- TS emit


def ts_type(schema: dict[str, Any], ctx: SchemaFile, by_stem: dict[str, SchemaFile], importing: set[Ref]) -> str:
    if "$ref" in schema:
        file, title, _ = resolve(schema["$ref"], ctx, by_stem)
        importing.add(Ref(file.stem, title))
        return title
    for combiner in ("anyOf", "oneOf"):
        if combiner in schema:
            return " | ".join(ts_type(s, ctx, by_stem, importing) for s in schema[combiner])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    typ = schema.get("type")
    if isinstance(typ, list):
        return " | ".join(ts_type({**schema, "type": t}, ctx, by_stem, importing) for t in typ)
    if typ == "array":
        item = ts_type(schema["items"], ctx, by_stem, importing) if "items" in schema else "unknown"
        return f"Array<{item}>"
    if typ == "object" or (typ is None and ("properties" in schema or "additionalProperties" in schema)):
        props = schema.get("properties") or {}
        extra = schema.get("additionalProperties", True)
        if not props:
            if isinstance(extra, dict):
                return f"Record<string, {ts_type(extra, ctx, by_stem, importing)}>"
            return "Record<string, unknown>"
        return _ts_inline_object(props, set(schema.get("required") or []), ctx, by_stem, importing)
    if typ in SCALAR_TS:
        return SCALAR_TS[typ]
    sys.exit(f"{ctx.path.name}: cannot map to TypeScript: {json.dumps(schema)[:120]}")


def _ts_inline_object(
    props: dict[str, Any], required: set[str], ctx: SchemaFile, by_stem: dict[str, SchemaFile], importing: set[Ref]
) -> str:
    fields = []
    for name, prop in props.items():
        optional = "" if name in required else "?"
        fields.append(f"readonly {name}{optional}: {ts_type(prop, ctx, by_stem, importing)}")
    return "{ " + "; ".join(fields) + " }"


def _ts_decl(title: str, sub: dict[str, Any], ctx: SchemaFile, by_stem: dict[str, SchemaFile], importing: set[Ref]) -> str:
    for combiner in ("anyOf", "oneOf"):
        if combiner in sub:
            parts = [ts_type(s, ctx, by_stem, importing) for s in sub[combiner]]
            return f"export type {title} = {' | '.join(parts)};"
    if "enum" in sub or "const" in sub:
        return f"export type {title} = {ts_type(sub, ctx, by_stem, importing)};"
    props = sub.get("properties") or {}
    if not props:
        return f"export type {title} = {ts_type(sub, ctx, by_stem, importing)};"
    lines = [f"export interface {title} {{"]
    required = set(sub.get("required") or [])
    for name, prop in props.items():
        optional = "" if name in required else "?"
        lines.append(f"  readonly {name}{optional}: {ts_type(prop, ctx, by_stem, importing)};")
    lines.append("}")
    return "\n".join(lines)


def emit_ts(schemas: list[SchemaFile], emittable: dict[Ref, Any], by_stem: dict[str, SchemaFile]) -> dict[str, str]:
    per_file: dict[str, list[Ref]] = {}
    for ref in emittable:
        per_file.setdefault(ref.file, []).append(ref)
    files: dict[str, str] = {}
    index_exports: list[str] = []
    for schema_file in schemas:
        refs = per_file.get(schema_file.stem)
        if not refs:
            continue
        importing: set[Ref] = set()
        blocks = [_ts_decl(ref.title, emittable[ref], schema_file, by_stem, importing) for ref in sorted(refs)]
        imports: list[str] = []
        for dep_file in sorted({r.file for r in importing if r.file != schema_file.stem}):
            titles = sorted(r.title for r in importing if r.file == dep_file)
            imports.append(f'import type {{ {", ".join(titles)} }} from "./{dep_file}";')
        files[f"generated/ts/{schema_file.stem}.ts"] = "\n".join(imports + [""] + blocks) + "\n"
        index_exports.append(f'export * from "./{schema_file.stem}";')
    files["generated/ts/index.ts"] = "\n".join(index_exports) + "\n"
    return files


# ------------------------------------------------------------- EventHub emit
#
# The EventHub (#878) consumes the [[channel]] rows of methods.toml as a
# generated registry so channel names, payload/snapshot bindings and the
# durable default cannot drift from the contracts. Emitted inside
# frontend/src so no bundler alias or fs.allow config is needed.


CHANNEL_PATTERN = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)*$")
EVENTHUB_TS_IMPORT_BASE = "../../../../contracts/generated/ts"


def emit_ts_channels(methods: dict[str, Any]) -> str:
    rows = methods.get("channel", [])
    if not rows:
        sys.exit("methods.toml: at least one [[channel]] row is required")
    seen: set[str] = set()
    entries: list[tuple[str, Ref, Ref, bool, list[str], list[str], str]] = []
    for row in rows:
        name = row.get("name", "")
        if not CHANNEL_PATTERN.match(name):
            sys.exit(f"methods.toml: channel name {name!r} does not match {CHANNEL_PATTERN.pattern}")
        if name in seen:
            sys.exit(f"methods.toml: duplicate channel {name!r}")
        seen.add(name)
        entries.append(
            (
                name,
                _split_ref(row["payload"]),
                _split_ref(row["snapshot"]),
                bool(row.get("durable_default", False)),
                [str(p) for p in row.get("producers", [])],
                [str(c) for c in row.get("consumers", [])],
                str(row.get("notes", "")),
            )
        )
    importing = {ref for _, payload, snapshot, *_ in entries for ref in (payload, snapshot)}
    imports = []
    for dep_file in sorted({r.file for r in importing}):
        titles = sorted(r.title for r in importing if r.file == dep_file)
        imports.append(
            f'import type {{ {", ".join(titles)} }} from "{EVENTHUB_TS_IMPORT_BASE}/{dep_file}";'
        )
    lines = imports + [""]
    names = ", ".join(json.dumps(name) for name, *_ in entries)
    lines.append(f"export const CHANNEL_NAMES = [{names}] as const;")
    lines.append("export type ChannelName = (typeof CHANNEL_NAMES)[number];")
    lines.append("")
    lines.append("export interface ChannelSpec<P, S> {")
    lines.append("  readonly name: ChannelName;")
    lines.append("  readonly payloadTitle: string;")
    lines.append("  readonly snapshotTitle: string;")
    lines.append("  readonly durableDefault: boolean;")
    lines.append("  readonly producers: readonly string[];")
    lines.append("  readonly consumers: readonly string[];")
    lines.append("  readonly notes: string;")
    lines.append("}")
    lines.append("")
    lines.append("export interface ChannelRegistry {")
    for name, payload, snapshot, *_ in entries:
        lines.append(f"  readonly {json.dumps(name)}: ChannelSpec<{payload.title}, {snapshot.title}>;")
    lines.append("}")
    lines.append("")
    lines.append("export const CHANNEL_REGISTRY: ChannelRegistry = {")
    for name, payload, snapshot, durable, producers, consumers, notes in entries:
        lines.append(f"  {json.dumps(name)}: {{")
        lines.append(f"    name: {json.dumps(name)},")
        lines.append(f"    payloadTitle: {json.dumps(payload.title)},")
        lines.append(f"    snapshotTitle: {json.dumps(snapshot.title)},")
        lines.append(f"    durableDefault: {'true' if durable else 'false'},")
        lines.append(f"    producers: [{', '.join(json.dumps(p) for p in producers)}],")
        lines.append(f"    consumers: [{', '.join(json.dumps(c) for c in consumers)}],")
        lines.append(f"    notes: {json.dumps(notes)},")
        lines.append("  },")
    lines.append("};")
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------- Python emit


def py_type(schema: dict[str, Any], ctx: SchemaFile, by_stem: dict[str, SchemaFile]) -> str:
    if "$ref" in schema:
        _, title, _ = resolve(schema["$ref"], ctx, by_stem)
        return title
    for combiner in ("anyOf", "oneOf"):
        if combiner in schema:
            return " | ".join(f"({py_type(s, ctx, by_stem)})" for s in schema[combiner])
    if "const" in schema:
        value = schema["const"]
        if value is True:
            return "Literal[True]"
        if value is False:
            return "Literal[False]"
        if value is None:
            return "None"
        return f"Literal[{json.dumps(value)}]"
    if "enum" in schema:
        return "str"
    typ = schema.get("type")
    if isinstance(typ, list):
        return " | ".join(py_type({**schema, "type": t}, ctx, by_stem) for t in typ)
    if typ == "array":
        item = py_type(schema["items"], ctx, by_stem) if "items" in schema else "Any"
        return f"list[{item}]"
    if typ == "object" or (typ is None and ("properties" in schema or "additionalProperties" in schema)):
        props = schema.get("properties") or {}
        extra = schema.get("additionalProperties", True)
        if not props:
            if isinstance(extra, dict):
                return f"dict[str, {py_type(extra, ctx, by_stem)}]"
            return "dict[str, Any]"
        return title_of(ctx, schema)
    if typ in SCALAR_PY:
        return SCALAR_PY[typ]
    sys.exit(f"{ctx.path.name}: cannot map to Python: {json.dumps(schema)[:120]}")


def title_of(ctx: SchemaFile, sub: dict[str, Any]) -> str:
    for title, candidate in ctx.titles.items():
        if candidate is sub:
            return title
    if sub is ctx.raw and ctx.raw.get("title"):
        return ctx.raw["title"]
    sys.exit(f"{ctx.path.name}: inline object without a $defs title is not emittable; give it a $defs entry")


def _py_decl(title: str, sub: dict[str, Any], ctx: SchemaFile, by_stem: dict[str, SchemaFile]) -> tuple[str, str]:
    """Returns (kind, text) where kind is 'class' or 'alias'.

    Aliases must be emitted after classes: module-level ``X = A | B``
    evaluates eagerly even with postponed annotations.
    """
    for combiner in ("anyOf", "oneOf"):
        if combiner in sub:
            parts = " | ".join(py_type(s, ctx, by_stem) for s in sub[combiner])
            return "alias", f"{title} = {parts}"
    if "enum" in sub:
        members = "\n".join(f"    {str(value).upper()} = {json.dumps(value)}" for value in sub["enum"])
        return "class", f"class {title}(str, enum.Enum):\n{members}"
    props = sub.get("properties") or {}
    if not props:
        return "alias", f"{title} = {py_type(sub, ctx, by_stem)}"
    required = [n for n in (sub.get("required") or []) if n in props]
    optional = [n for n in props if n not in required]
    lines = ["@dataclass(frozen=True)", f"class {title}:"]
    for name in required:
        lines.append(f"    {name}: {py_type(props[name], ctx, by_stem)}")
    for name in optional:
        mapped = py_type(props[name], ctx, by_stem)
        needs_parens = " | " in mapped or mapped.startswith(("list[", "dict["))
        lines.append(f"    {name}: {'(' + mapped + ')' if needs_parens else mapped} | None = None")
    return "class", "\n".join(lines)


def emit_python(emittable: dict[Ref, Any], by_stem: dict[str, SchemaFile]) -> str:
    decls = [_py_decl(ref.title, emittable[ref], by_stem[ref.file], by_stem) for ref in sorted(emittable)]
    decls.sort(key=lambda d: 0 if d[0] == "class" else 1)
    lines = [
        '"""Generated bridge-contract types. Typing-only: boundary validation of',
        "envelopes is the bridge package's job (#875).",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "import enum",
        "from dataclasses import dataclass",
        "from typing import Any, Literal",
        "",
    ]
    for _, text in decls:
        lines.append(text)
        lines.append("")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# ---------------------------------------------------------------- Rust emit


def rs_type(schema: dict[str, Any], ctx: SchemaFile, by_stem: dict[str, SchemaFile]) -> str:
    if "$ref" in schema:
        _, title, _ = resolve(schema["$ref"], ctx, by_stem)
        return title
    for combiner in ("anyOf", "oneOf"):
        if combiner in schema:
            sys.exit(f"{ctx.path.name}: bare anyOf/oneOf needs a titled $defs wrapper for Rust")
    if "const" in schema:
        return {"str": "String", "int": "i64", "float": "f64", "bool": "bool"}.get(
            type(schema["const"]).__name__, "String"
        )
    if "enum" in schema:
        return "String"
    typ = schema.get("type")
    if isinstance(typ, list):
        # Scalar unions (e.g. JSON-RPC `id`: string|integer|null) degrade to
        # an arbitrary JSON value; the framing layer (#875) narrows them.
        return "serde_json::Value"
    if typ == "array":
        item = rs_type(schema["items"], ctx, by_stem) if "items" in schema else "serde_json::Value"
        return f"Vec<{item}>"
    if typ == "object" or (typ is None and ("properties" in schema or "additionalProperties" in schema)):
        props = schema.get("properties") or {}
        extra = schema.get("additionalProperties", True)
        if not props:
            value = rs_type(extra, ctx, by_stem) if isinstance(extra, dict) else "serde_json::Value"
            return f"std::collections::HashMap<String, {value}>"
        return title_of(ctx, schema)
    if typ in SCALAR_RS:
        return SCALAR_RS[typ]
    sys.exit(f"{ctx.path.name}: cannot map to Rust: {json.dumps(schema)[:120]}")


def _rs_variant_name(type_name: str) -> str:
    for suffix in ("Response", "Result", "Payload", "Snapshot", "Params"):
        if type_name.endswith(suffix) and len(type_name) > len(suffix):
            return type_name[: -len(suffix)]
    return type_name


def _rs_decl(title: str, sub: dict[str, Any], ctx: SchemaFile, by_stem: dict[str, SchemaFile]) -> str:
    if "enum" in sub:
        for value in sub["enum"]:
            if not RUST_ENUM_VALUE.match(str(value)):
                sys.exit(f"{ctx.path.name}: enum value {value!r} is not a Rust-safe identifier")
        variants = "\n".join(f"    {str(value).title().replace('_', '')}," for value in sub["enum"])
        return (
            "#[derive(Serialize, Deserialize, Debug, Clone, PartialEq)]\n"
            '#[serde(rename_all = "snake_case")]\n'
            f"pub enum {title} {{\n{variants}\n}}"
        )
    for combiner in ("anyOf", "oneOf"):
        if combiner in sub:
            fields = ",\n    ".join(
                f"{_rs_variant_name(rs_type(s, ctx, by_stem))}({rs_type(s, ctx, by_stem)})" for s in sub[combiner]
            )
            return (
                "#[derive(Serialize, Deserialize, Debug, Clone, PartialEq)]\n"
                "#[serde(untagged)]\n"
                f"pub enum {title} {{\n    {fields},\n}}"
            )
    props = sub.get("properties") or {}
    if not props:
        return f"pub type {title} = {rs_type(sub, ctx, by_stem)};"
    required = set(sub.get("required") or [])
    lines = ["#[derive(Serialize, Deserialize, Debug, Clone, PartialEq)]", f"pub struct {title} {{"]
    for name, prop in props.items():
        mapped = rs_type(prop, ctx, by_stem)
        if "const" in prop:
            lines.append(f"    /// must be {json.dumps(prop['const'])} (enforced by the framing layer, #875)")
        if name not in required:
            lines.append('    #[serde(default, skip_serializing_if = "Option::is_none")]')
            lines.append(f"    pub {name}: Option<{mapped}>,")
        else:
            lines.append(f"    pub {name}: {mapped},")
    lines.append("}")
    return "\n".join(lines)


def emit_rust(emittable: dict[Ref, Any], by_stem: dict[str, SchemaFile]) -> str:
    lines = [
        "// `const` fields degrade to their scalar type; the framing layer (#875)",
        "// enforces exact values.",
        "",
        "use serde::{Deserialize, Serialize};",
        "",
    ]
    for ref in sorted(emittable, key=lambda r: (r.file, r.title)):
        lines.append(_rs_decl(ref.title, emittable[ref], by_stem[ref.file], by_stem))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# ------------------------------------------------------------------- hashes


def build_outputs() -> dict[str, str]:
    schemas, methods = load_inputs()
    by_stem = {s.stem: s for s in schemas}
    emittable = collect_emittable(schemas, methods)

    sources = [(ROOT / "methods.toml").read_bytes()] + [s.path.read_bytes() for s in schemas]
    entries = sorted(
        (hashlib.sha256(data).hexdigest(), f"contracts/{path}")
        for data, path in zip(
            sources, ["methods.toml"] + [f"schemas/{s.path.relative_to(SCHEMAS)}" for s in schemas], strict=True
        )
    )
    body = [f"{digest}  {path}" for digest, path in entries]
    total = hashlib.sha256("\n".join(body).encode()).hexdigest()
    banner = f"contract hash {total}"

    outputs = emit_ts(schemas, emittable, by_stem)
    outputs["generated/python/contracts_generated.py"] = emit_python(emittable, by_stem)
    outputs["generated/rust/contracts.rs"] = emit_rust(emittable, by_stem)
    outputs["../frontend/src/eventhub/generated/channels.ts"] = emit_ts_channels(methods)
    outputs["CONTRACTS.sha256"] = "# " + GENERATED_MARK + ". Do not edit.\n" + f"total  {total}\n" + "\n".join(body) + "\n"
    for rel, text in list(outputs.items()):
        marker = "#" if rel.endswith(".py") else "//"
        outputs[rel] = _stamp(text, marker, banner)
    return outputs


def _stamp(text: str, marker: str, banner: str) -> str:
    first, _, rest = text.partition("\n")
    if first.startswith(f"{marker} GENERATED — contract hash"):
        return f"{marker} GENERATED — {banner}.\n{rest}"
    return f"{marker} GENERATED — {banner}. Do not edit; edit the schema and regenerate.\n{text}"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if any generated file or the manifest would change")
    args = parser.parse_args()

    outputs = build_outputs()
    if args.check:
        drifted = [
            rel
            for rel, content in sorted(outputs.items())
            if not (ROOT / rel).exists() or (ROOT / rel).read_text(encoding="utf-8") != content
        ]
        if drifted:
            print("contracts drift detected; run `python contracts/generate.py` and commit the result:")
            for rel in drifted:
                print(f"  {rel}")
            sys.exit(1)
        print(f"contracts fresh ({len(outputs)} outputs)")
        return
    for rel, content in outputs.items():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    print(f"generated {len(outputs)} files")


if __name__ == "__main__":
    main()
