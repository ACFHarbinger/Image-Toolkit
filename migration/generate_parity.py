"""Render docs/migration/parity.md from the migration ledger (W0-18 / #882).

Source of truth: migration/features.toml. The output is committed and CI
freshness-checks it with ``--check``, mirroring contracts/generate.py.

Example:
    >>> python migration/generate_parity.py            # rewrite the doc
    >>> python migration/generate_parity.py --check    # fail on drift
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
LEDGER_REL = Path("migration/features.toml")
OUTPUT_REL = Path("docs/migration/parity.md")

GENERATED_MARK = "GENERATED by migration/generate_parity.py"
ISSUE_URL = "https://github.com/ACFHarbinger/Image-Toolkit/issues"

STATUS_ORDER = ("pyside-only", "both", "parity-passed", "pyside-deleted")


def _load_ledger(root: Path) -> dict[str, Any]:
    return tomllib.loads((root / LEDGER_REL).read_text(encoding="utf-8"))


def _os_progress(feature: dict[str, Any]) -> str:
    checklist = feature["os_checklist"]
    if not checklist:
        return "—"
    done = sum(1 for item in checklist if item["checked"])
    return f"{done}/{len(checklist)}"


def _wave_table(wave: str, features: list[dict[str, Any]]) -> list[str]:
    lines = [
        f"## {wave}",
        "",
        "| id | title | owner | issue | status | routes | os checklist | scenarios |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for feature in features:
        routes = "<br>".join(feature["routes"]) or "—"
        lines.append(
            "| {id} | {title} | {owner} | [#{issue}]({url}/{issue}) | {status} | {routes} | {os} | {scenarios} |".format(
                id=feature["id"],
                title=feature["title"],
                owner=feature["owner"],
                issue=feature["issue"],
                url=ISSUE_URL,
                status=feature["status"],
                routes=routes,
                os=_os_progress(feature),
                scenarios=len(feature["scenarios"]),
            )
        )
    lines.append("")
    return lines


def render(ledger: dict[str, Any]) -> str:
    features = ledger.get("feature", [])
    counts = {status: 0 for status in STATUS_ORDER}
    for feature in features:
        counts[feature["status"]] = counts.get(feature["status"], 0) + 1

    lines = [
        f"<!-- {GENERATED_MARK} — do not edit -->",
        "",
        "# Migration parity",
        "",
        "One row per capability in `migration/features.toml` (W0-18 / #882);",
        "the status lifecycle and deletion gate are documented in",
        "`migration/README.md`. Regenerate with `python migration/generate_parity.py`.",
        "",
        "## Summary",
        "",
        f"- {len(features)} feature rows: " + ", ".join(f"{status} × {counts[status]}" for status in STATUS_ORDER),
        "",
    ]

    waves = sorted({feature["wave"] for feature in features})
    for wave in waves:
        rows = sorted((f for f in features if f["wave"] == wave), key=lambda f: f["id"])
        lines.extend(_wave_table(wave, rows))

    lines.extend(["## Shared Qt infrastructure", ""])
    shared = ledger.get("shared", [])
    if shared:
        lines.extend(["| path | owner | note |", "|---|---|---|"])
        for entry in sorted(shared, key=lambda item: item["path"]):
            lines.append(f"| `{entry['path']}` | {entry['owner']} | {entry['note']} |")
    else:
        lines.append("None.")
    lines.append("")

    lines.extend(["## Exceptions", ""])
    exceptions = ledger.get("exception", [])
    if exceptions:
        lines.extend(["| feature | path | reason | issue | approved_by | expires |", "|---|---|---|---|---|---|"])
        for record in exceptions:
            lines.append(
                "| {feature} | `{path}` | {reason} | [#{issue}]({url}/{issue}) | {approved_by} | {expires} |".format(
                    feature=record["feature"],
                    path=record["path"],
                    reason=record["reason"],
                    issue=record["issue"],
                    url=ISSUE_URL,
                    approved_by=record["approved_by"],
                    expires=record.get("expires", "—"),
                )
            )
    else:
        lines.append("None.")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed parity doc would change")
    parser.add_argument("--root", type=Path, default=ROOT, help="repository root (default: auto-detect)")
    args = parser.parse_args()

    content = render(_load_ledger(args.root))
    output = args.root / OUTPUT_REL
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != content:
            print("parity doc drift detected; run `python migration/generate_parity.py` and commit the result:")
            print(f"  {OUTPUT_REL}")
            sys.exit(1)
        print(f"parity doc fresh ({OUTPUT_REL})")
        return
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")
    print(f"generated {OUTPUT_REL}")


if __name__ == "__main__":
    main()
