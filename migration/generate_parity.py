"""Generate docs/migration/parity.md from the migration ledger (W0-18, #882).

The parity doc is a read-only view of `migration/features.toml`; the ledger
is the source of truth. Never hand-edit the output — CI runs this script
with `--check` and fails on drift (same pattern as contracts/generate.py).

Example:
    >>> python migration/generate_parity.py            # rewrite the doc
    >>> python migration/generate_parity.py --check    # freshness check
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from middleware.validation.check_migration_ledger import (  # noqa: E402
    LEDGER_REL,
    Feature,
    parse_ledger,
)

OUTPUT_REL = Path("docs/migration/parity.md")

_STATUS_LABEL = {
    "pyside-only": "PySide6 only",
    "both": "Both shells",
    "parity-passed": "Parity passed",
    "pyside-deleted": "PySide6 deleted",
}

_OS_LABEL = {
    "pending": "pending",
    "automated": "automated",
    "passed": "passed",
    "na": "n/a",
}

_WAVE_ORDER = {"retire": 99}


def _wave_key(feature: Feature) -> tuple[int, str]:
    wave = feature.wave
    head = wave.rstrip("abcdef")
    try:
        order = int(head)
    except ValueError:
        order = _WAVE_ORDER.get(wave, 50)
    return order, wave


def _route_text(feature: Feature) -> str:
    parts: list[str] = []
    for route in feature.routes:
        if route.alias:
            parts.append(f"`{route.old}` → `{route.to}` (alias: {route.alias})")
        elif route.old:
            parts.append(f"`{route.old}` → `{route.to}`")
        else:
            parts.append(f"`{route.to}`")
    return "<br>".join(parts) if parts else "—"


def _os_text(feature: Feature) -> str:
    return "<br>".join(f"{entry.os}: {_OS_LABEL.get(entry.status, entry.status)}" for entry in feature.os_checklist)


def render(features: list[Feature], contracts_hash: str) -> str:
    lines: list[str] = [
        "<!-- GENERATED by migration/generate_parity.py from migration/features.toml. Do not edit. -->",
        "",
        "# Migration parity",
        "",
        "The migration ledger (`migration/features.toml`, W0-18) is the source of",
        "truth; this page is its generated view. A row's PySide6 code is deleted",
        "only when parity evidence is green, its OS checklist is ticked, and",
        "Harbinger has signed off (see the roadmap's migration mechanics).",
        "",
        f"Contracts hash pinned by the ledger: `{contracts_hash}`.",
        "",
    ]

    counts: dict[str, int] = {}
    for feature in features:
        counts[feature.status] = counts.get(feature.status, 0) + 1
    summary = ", ".join(
        f"**{_STATUS_LABEL[status]}**: {counts.get(status, 0)}" for status in _STATUS_LABEL
    )
    lines += ["## Status summary", "", summary, ""]

    current_wave: str | None = None
    for feature in sorted(features, key=lambda item: (_wave_key(item), item.id)):
        if feature.wave != current_wave:
            current_wave = feature.wave
            lines += [f"## Wave {current_wave}", ""]
        lines += [
            f"### {feature.title} (`{feature.id}`)",
            "",
            f"- **Issue:** #{feature.issue}",
            f"- **Owner:** {feature.owner}",
            f"- **Status:** {_STATUS_LABEL.get(feature.status, feature.status)}",
            f"- **Routes:** {_route_text(feature)}",
            f"- **OS checklist:** {_os_text(feature)}",
            f"- **Scenarios:** {', '.join(f'`{scenario}`' for scenario in feature.scenarios)}",
        ]
        if feature.service:
            lines.append(f"- **Service:** `{feature.service}`")
        if feature.contract:
            lines.append(f"- **Contract:** `{feature.contract}`")
        docs = ", ".join(f"`{path}`" for path in feature.docs) if feature.docs else "—"
        lines.append(f"- **Docs:** {docs}")
        if feature.notes:
            lines.append(f"- **Notes:** {feature.notes}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="repository root (default: auto-detect)",
    )
    parser.add_argument("--output", type=Path, default=None, help=f"output path (default: {OUTPUT_REL})")
    parser.add_argument("--check", action="store_true", help="fail if the output is stale")
    args = parser.parse_args(argv)

    root: Path = args.root
    ledger_path = root / LEDGER_REL
    try:
        ledger = parse_ledger(tomllib.loads(ledger_path.read_text(encoding="utf-8")))
    except (OSError, tomllib.TOMLDecodeError) as exc:
        print(f"cannot read {LEDGER_REL}: {exc}", file=sys.stderr)
        return 2
    if ledger.errors:
        for error in ledger.errors:
            print(f"FAIL {error}", file=sys.stderr)
        print("fix the ledger before regenerating the parity doc", file=sys.stderr)
        return 1

    rendered = render(ledger.features, ledger.contracts_hash)
    output = args.output or root / OUTPUT_REL
    if args.check:
        current = output.read_text(encoding="utf-8") if output.is_file() else ""
        if current != rendered:
            print(
                f"FAIL {output.relative_to(root) if output.is_relative_to(root) else output} is stale; "
                "run `python migration/generate_parity.py`",
                file=sys.stderr,
            )
            return 1
        print(f"PASS {OUTPUT_REL} is fresh")
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(rendered, encoding="utf-8")
    print(f"wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
