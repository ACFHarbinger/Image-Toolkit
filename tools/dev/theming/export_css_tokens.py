#!/usr/bin/env python3
"""Export portable theme token JSON to CSS custom properties (#574, #575, #871).

Reads ``gui/src/theming/tokens/{dark,light}.json`` and writes ``:root`` blocks
with ``--it-color-*`` variables. Single-file mode feeds the docs website and
devtool app; ``--paired`` writes the light defaults plus a
``[data-theme="dark"]`` override block for the Tauri frontend shell.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
TOKENS_DIR = REPO_ROOT / "gui/src/theming/tokens"

CSS_VAR_MAP = {
    "accent": "accent",
    "surface": "surface",
    "window_bg": "window-bg",
    "text": "text",
    "muted_text": "muted-text",
    "border": "border",
    "accent_hover": "accent-hover",
    "accent_pressed": "accent-pressed",
}


def _load_tokens(path: Path) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))
    colors = data.get("colors")
    if not isinstance(colors, dict):
        raise ValueError(f"{path}: missing 'colors' object")
    return colors


def _var_block(selector: str, colors: dict[str, str]) -> list[str]:
    lines = [f"{selector} {{"]
    for key, css_suffix in CSS_VAR_MAP.items():
        value = colors.get(key)
        if not value:
            raise KeyError(f"Missing color token {key!r}")
        lines.append(f"  --it-color-{css_suffix}: {value};")
    lines.append("}")
    return lines


def tokens_to_css(colors: dict[str, str], *, surface: str) -> str:
    lines = [
        "/* Generated by tools/dev/theming/export_css_tokens.py — do not edit. */",
        f"/* surface: {surface} */",
    ]
    lines += _var_block(":root", colors)
    lines.append("")
    return "\n".join(lines)


def paired_tokens_to_css(light: dict[str, str], dark: dict[str, str]) -> str:
    """Light defaults on ``:root`` with a ``[data-theme="dark"]`` override."""
    lines = [
        "/* Generated by tools/dev/theming/export_css_tokens.py — do not edit. */",
        "/* surface: frontend (light + dark pair) */",
    ]
    lines += _var_block(":root", light)
    lines.append("")
    lines += _var_block(':root[data-theme="dark"]', dark)
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        type=Path,
        default=None,
        help=("Token JSON file. Defaults to dark.json in single mode and light.json with --paired."),
    )
    parser.add_argument(
        "--surface",
        choices=("docs", "dev", "raw", "frontend"),
        default="raw",
        help="Target surface hint (docs/dev); output format is the same shared token block.",
    )
    parser.add_argument(
        "--paired",
        action="store_true",
        help=(
            "Emit the light defaults on :root plus a [data-theme=dark] override block (reads tokens/{light,dark}.json)."
        ),
    )
    parser.add_argument(
        "--input-dark",
        type=Path,
        default=TOKENS_DIR / "dark.json",
        help="Dark token JSON file for --paired (default: gui/src/theming/tokens/dark.json).",
    )
    parser.add_argument(
        "--out",
        type=Path,
        required=True,
        help="Output CSS file path",
    )
    args = parser.parse_args(argv)

    if args.input is not None:
        input_path = args.input if args.input.is_absolute() else REPO_ROOT / args.input
    else:
        input_path = TOKENS_DIR / ("light.json" if args.paired else "dark.json")
    dark_path = args.input_dark if args.input_dark.is_absolute() else REPO_ROOT / args.input_dark
    out_path = args.out if args.out.is_absolute() else REPO_ROOT / args.out

    if args.paired:
        css = paired_tokens_to_css(_load_tokens(input_path), _load_tokens(dark_path))
    else:
        css = tokens_to_css(_load_tokens(input_path), surface=args.surface)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(css, encoding="utf-8")
    try:
        shown = out_path.relative_to(REPO_ROOT)
    except ValueError:
        shown = out_path
    print(f"Wrote {shown} ({len(CSS_VAR_MAP)} tokens)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
